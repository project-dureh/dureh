            "- Search only inside your WI worktree, the site, scratch space or the harness: a `find`, `grep -r`, `rg`, `du`,"
            " `ls -R` or `tree` rooted elsewhere (`/`, `/work`, `/nas`, `/proj`, `/home`, `~`) is refused. Do not leave"
