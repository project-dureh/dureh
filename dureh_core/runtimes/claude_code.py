"""Claude Code adapter.

generate(): writes CLAUDE.md, .claude/settings.json, .claude/agents/*.md,
.claude/skills/*/SKILL.md, and bin/dureh into the site. These files are
generated output, not the source of truth (org/ and the package are).

The dispatch contract maps to Claude Code as follows:
  spawn  -> the calling agent (desk or manager) uses the Agent tool with a brief
            printed by `dureh dispatch brief`; the PreToolUse hook admits the
            spawn only for a recorded, unconsumed brief and appends wi.dispatched.
  stop   -> the runtime's task stop, recorded by `dureh dispatch stop`.
  status -> SubagentStart/SubagentStop hooks append agent.started/finished and
            an agent run record with transcript token usage.
  wait   -> runtime notification; the brief states the bounded report format.
"""
