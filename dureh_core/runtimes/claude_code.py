def _model_id(entry: dict) -> str:
    model = entry["model"]
    provider, _, name = model.partition(":")
    if not name:
        return model
    if provider != "anthropic":
        raise DurehError(f"the claude-code adapter cannot host provider {provider!r}; map this tier to an anthropic model")
    return name


def _persona(site: Site) -> dict:
    p = site.state / "persona" / "persona.json"
    return json.loads(p.read_text(encoding="utf-8")) if p.is_file() else {}


def _skill_frontmatter(name: str, text: str) -> str:
    if text.startswith("---\n"):
        return text
    first = next((l.lstrip("# ").strip() for l in text.splitlines() if l.strip()), name)
    return f"---\nname: {name}\ndescription: {first}. CAMRI package skill installed by DUREH.\n---\n\n{text}"


