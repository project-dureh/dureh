def _hook_command(site: Site) -> str:
    return f"{shlex.quote(str(HARNESS_ROOT / 'dureh'))} --site {shlex.quote(str(site.root))} hook claude-code"


def _settings(site: Site) -> dict:
    cmd = _hook_command(site)
    hook = lambda timeout=30: [{"type": "command", "command": cmd, "timeout": timeout}]
    desk_model = _model_id(site.model_for_tier("desk"))
    dureh = str(site.root / "bin" / "dureh")
    return {
        "$comment": "Generated by dureh adapter claude-code. Hooks are a workflow control, not an OS sandbox.",
        "model": desk_model,
        "autoMemoryEnabled": False,
        "env": {**{str(k): str(v) for k, v in ((site.config.get("env") or {}).get("vars") or {}).items()},
                **({"PATH": os.pathsep.join([*prepend, os.environ.get("PATH", "")])} if (prepend := (site.config.get("env") or {}).get("path_prepend")) else {}),
                "DUREH_SITE": str(site.root), "DUREH_ROOT": str(HARNESS_ROOT)},
        "permissions": {
            "allow": [f"Bash({dureh} *)", "Read", "Grep", "Glob"],
            "deny": ["Bash(git push *)", "Bash(sbatch *)", "Bash(rm -rf *)"],
        },
        "hooks": {
            "SessionStart": [{"hooks": hook(60)}],
            "SessionEnd": [{"hooks": hook(120)}],
            "PreToolUse": [{"matcher": "Write|Edit|MultiEdit|NotebookEdit|Bash|Agent|Task|WebFetch|WebSearch", "hooks": hook()}],
            "PostToolUse": [{"matcher": "Write|Edit|MultiEdit", "hooks": hook()}],
            "SubagentStart": [{"hooks": hook()}],
            "SubagentStop": [{"hooks": hook()}],
        },
    }


def generate(site: Site) -> dict:
    root = site.root
    (root / ".claude" / "agents").mkdir(parents=True, exist_ok=True)
    (root / ".claude" / "skills").mkdir(parents=True, exist_ok=True)
    (root / "bin").mkdir(exist_ok=True)
    files: dict[str, str] = {}
    files["bin/dureh"] = ("#!/usr/bin/env sh\n# generated by dureh adapter claude-code\n"
                          f"exec {shlex.quote(str(HARNESS_ROOT / 'dureh'))} --site {shlex.quote(str(root))} \"$@\"\n")
    files["CLAUDE.md"] = _claude_md(site)
    files[".claude/settings.json"] = json.dumps(_settings(site), indent=2) + "\n"
    for role in site.org.roles.values():
        if role.kind != "desk":
            files[f".claude/agents/{role.name}.md"] = _agent_file(site, role)
    for skill in sorted((site.startup / "skills").glob("*/SKILL.md")):
        name = skill.parent.name
        files[f".claude/skills/{name}/SKILL.md"] = _skill_frontmatter(name, skill.read_text(encoding="utf-8"))
    org_skills = HARNESS_ROOT / "org" / "skills"
    for skill in sorted(org_skills.glob("*/SKILL.md")):
        files[f".claude/skills/{skill.parent.name}/SKILL.md"] = _skill_frontmatter(skill.parent.name, skill.read_text(encoding="utf-8"))
    # remove stale generated agents/skills from a previous generation
    manifest_path = root / ".claude" / ".dureh-generated.json"
    old = json.loads(manifest_path.read_text()) if manifest_path.is_file() else {"files": {}}
    for rel in old.get("files", {}):
        if rel not in files and (root / rel).is_file():
            (root / rel).unlink()
    for rel, text in files.items():
        p = root / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        write_replace(p, text, 0o755 if rel == "bin/dureh" else 0o644)
    manifest = {"adapter": "claude-code", "generated_at": utc_now(),
                "files": {rel: sha256_bytes(text.encode("utf-8")) for rel, text in files.items()}}
    write_replace(manifest_path, dumps(manifest))
    return manifest


def drift(site: Site) -> list[str]:
    manifest_path = site.root / ".claude" / ".dureh-generated.json"
    if not manifest_path.is_file():
        return ["adapter output was never generated"]
    out = []
    for rel, digest in json.loads(manifest_path.read_text())["files"].items():
        p = site.root / rel
        if not p.is_file():
            out.append(f"missing generated file {rel}")
        elif sha256_bytes(p.read_bytes()) != digest:
            out.append(f"generated file was edited by hand: {rel}")
    return out


# =================================================================== hooks
def _deny(reason: str, event: str = "PreToolUse") -> dict:
    return {"hookSpecificOutput": {"hookEventName": event, "permissionDecision": "deny",
                                   "permissionDecisionReason": f"DUREH: {reason}"}}


def _agent_wi(led: Ledger, agent_id: str | None) -> str | None:
    if not agent_id:
        return None
    for ev in reversed(led.load("event")):
        if ev["type"] == "agent.started" and ev["payload"].get("agent_id") == agent_id:
            return ev["wi"]
    return None


def _role_of(site: Site, data: dict) -> str:
    agent_type = data.get("agent_type")
    if not agent_type:
        return "desk"
    return agent_type if agent_type in site.org.roles and agent_type != "desk" else f"foreign:{agent_type}"


def _scheduler_only(site: Site) -> list[str]:
    guards = site.package_manifest().get("guards") or {}
    return DEFAULT_SCHEDULER_ONLY + list(guards.get("scheduler_only_commands") or [])


def _is_dureh(word: str, site: Site) -> bool:
    return word in ("dureh", str(site.root / "bin" / "dureh"), "bin/dureh", "./bin/dureh", str(HARNESS_ROOT / "dureh"))


_SEPARATORS = {";", "&&", "||", "|", "&", "\n", "|&", ";;"}
_REDIRECTS = {">", ">>", "&>", ">|", "2>", "2>>", "1>", "&>>"}
_WRAPPERS = {"timeout", "nice", "env", "command", "time", "stdbuf", "ionice", "xargs"}


def _segments(command: str) -> list[list[str]]:
    lex = shlex.shlex(command.replace("\n", " ; "), posix=True, punctuation_chars=";&|<>")
    lex.whitespace_split = True
    tokens = list(lex)
    segs, cur = [], []
    for t in tokens:
        if t in _SEPARATORS:
            segs.append(cur)
            segs.append([t])
            cur = []
        else:
            cur.append(t)
    segs.append(cur)
    return [s for s in segs if s]


def guard_bash(site: Site, role: str, data: dict) -> dict | None:
    ti = data.get("tool_input") or {}
    command = ti.get("command") or ""
    if ti.get("run_in_background"):
        return _deny("no hidden background work in the session; submit computation with `dureh slurm submit`")
    if "`" in command or "$(" in command:
        if role != "desk":
            return _deny("command substitution cannot be checked; run the parts as separate commands")
    try:
        segs = _segments(command)
    except ValueError as exc:
        return _deny(f"cannot parse the command ({exc}); simplify it")
    cwd = Path(data.get("cwd") or site.root)
    scheduler_only = _scheduler_only(site)
    words_only = [s for s in segs if s[0] not in _SEPARATORS]
    if any(s == ["&"] for s in segs):
        return _deny("no background jobs (`&`) in the session; use the scheduler")
    agent_id = data.get("agent_id")
    led = Ledger(site)
    agent_wi = _agent_wi(led, agent_id) if agent_id else None
    for seg in words_only:
        words = list(seg)
        env_assign = []
        while words and re.match(r"^[A-Za-z_][A-Za-z0-9_]*=", words[0]):
            env_assign.append(words.pop(0))
        if any(a.startswith("DUREH_") for a in env_assign):
            return _deny("DUREH_* variables are set by the harness, not by the command")
        while words and words[0] in _WRAPPERS:
            words.pop(0)
            while words and (words[0].startswith("-") or re.match(r"^\d+[smhd]?$", words[0])):
                words.pop(0)
        if not words:
            continue
        first = os.path.basename(words[0])
        if first in ALWAYS_DENY_FIRST:
            return _deny(ALWAYS_DENY_FIRST[first])
        if any(fnmatchcase(first, pat) for pat in scheduler_only):
            return _deny(f"`{first}` runs only as a scheduler job; use `dureh slurm submit`")
        if first == "git" and "push" in words[1:3]:
            return _deny("pushes go through `dureh push` with a Director decision bound to the revision")
        if first == "rm" and any(w.startswith("-") and ("r" in w or "R" in w) for w in words[1:]):
            return _deny("recursive deletion goes through `dureh purge`")
        if first == "cd" and len(words) > 1:
            cwd = (cwd / os.path.expanduser(words[1])).resolve()
            continue
        if _is_dureh(words[0], site):
            if len(words_only) != 1:
                return _deny("run a dureh command on its own, not combined with other commands")
            if "--actor" in words and words[words.index("--actor") + 1: words.index("--actor") + 2] != [role]:
                return _deny("--actor must be your own role; the hook sets identity")
            if "--site" in words and words[words.index("--site") + 1: words.index("--site") + 2] != [str(site.root)]:
                return _deny("dureh commands must target this site")
            prefix = f"DUREH_ACTOR={shlex.quote(role)} " + (f"DUREH_AGENT_ID={shlex.quote(agent_id)} " if agent_id else "")
            new_input = dict(ti)
            new_input["command"] = prefix + command
            return {"hookSpecificOutput": {"hookEventName": "PreToolUse", "permissionDecision": "allow",
                                           "permissionDecisionReason": "DUREH harness tool; identity set by hook",
                                           "updatedInput": new_input}}
        targets = []
        for i, w in enumerate(seg):
            if w in _REDIRECTS and i + 1 < len(seg):
                targets.append(seg[i + 1])
        args = [w for w in words[1:] if not w.startswith("-")]
        if first == "tee":
            targets += args
        elif first in ("cp", "mv", "install", "rsync", "ln") and args:
            targets.append(args[-1])
            if first == "mv":
                targets += args[:-1]
        elif first in ("rm", "mkdir", "touch", "rmdir", "truncate", "chmod", "chown"):
            targets += args[1:] if first in ("chmod", "chown") else args
        elif first == "sed" and any(w.startswith("-i") for w in words[1:]):
            targets += args[1:]
        elif first in ("git",) and len(words) > 1 and words[1] in ("mv", "rm"):
            targets += [w for w in words[2:] if not w.startswith("-")]
        for tgt in targets:
            if tgt in ("/dev/null", "/dev/stdout", "/dev/stderr") or tgt.startswith("&"):
                continue
            ok, why = write_decision(site, role, Path(os.path.expanduser(tgt)), cwd, agent_wi)
            if not ok:
                return _deny(f"write to {tgt}: {why}")
    return None


def pre_tool_use(site: Site, data: dict) -> dict | None:
    tool = data.get("tool_name") or ""
    role = _role_of(site, data)
    if role.startswith("foreign:"):
        if tool in WRITE_TOOLS | SPAWN_TOOLS or tool == "Bash":
            return _deny(f"{role[8:]} is not a DUREH role; spawn DUREH roles only")
        return None
    org = site.org
    led = Ledger(site)
    ti = data.get("tool_input") or {}
    if tool in SPAWN_TOOLS:
        target = ti.get("subagent_type") or "general-purpose"
        if target not in org.roles or target == "desk":
            return _deny(f"`{target}` is not a DUREH role; research goes to `researcher`, documents to `doc-writer`")
        if target not in org.role(role).may_dispatch:
            return _deny(f"{role} may not dispatch {target}")
        m = BRIEF_RE.search(ti.get("prompt") or "")
        if not m:
            return _deny(f"spawn needs a brief: run `{site.root}/bin/dureh dispatch brief --wi <WI>` and pass its output as the prompt")
        wi, brief_role, digest = m.groups()
        if brief_role != target:
            return _deny(f"the brief is for {brief_role}, not {target}")
        events = led.events(wi)
        prepared = [e for e in events if e["type"] == "dispatch.prepared" and e["payload"].get("brief") == digest]
        if not prepared:
            return _deny(f"no recorded brief {digest} for {wi}")
        if prepared[-1]["payload"].get("by") != role:
            return _deny(f"brief {digest} was prepared by {prepared[-1]['payload'].get('by')}, not {role}")
        consumed = [e for e in events if e["type"] in ("wi.dispatched", "checker.dispatched") and e["payload"].get("brief") == digest]
        if consumed:
            return _deny(f"brief {digest} was already used; prepare a new brief")
        try:
            etype = "checker.dispatched" if prepared[-1]["payload"].get("checking") else "wi.dispatched"
            led.event(etype, role, wi, {"role": target, "brief": digest, "by": role,
                                        "model": prepared[-1]["payload"].get("model"),
                                        "background": bool(ti.get("run_in_background"))}, [prepared[-1]["id"]])
        except DurehError as exc:
            return _deny(str(exc))
        return None
    if tool in WRITE_TOOLS:
        path = ti.get("file_path") or ti.get("notebook_path")
        if not path:
            return _deny("write without a path")
        agent_wi = _agent_wi(led, data.get("agent_id"))
        ok, why = write_decision(site, role, Path(path), Path(data.get("cwd") or site.root), agent_wi)
        if not ok:
            return _deny(why)
        t = classify(site, path)
        if t.zone == "desk-state" and t.site_rel.startswith("state/memory") and tool == "Write":
            cap = int(site.limit("memory_cap_bytes", 65536))
            mem = site.state / "memory"
            current = sum(f.stat().st_size for f in mem.rglob("*") if f.is_file() and f.resolve() != Path(path).resolve())
            new = len((ti.get("content") or "").encode("utf-8"))
            if current + new > cap:
                return _deny(f"desk memory would grow to {current + new} bytes, over the {cap}-byte cap; summarize first")
        return None
    if tool == "Bash":
        return guard_bash(site, role, data)
    if tool in NETWORK_TOOLS and role not in ("desk", "researcher"):
        return _deny("network access is limited to the desk and researcher")
    return None


def post_tool_use(site: Site, data: dict) -> None:
    ti = data.get("tool_input") or {}
    path = ti.get("file_path")
    if not path or _role_of(site, data) != "desk":
        return None
    t = classify(site, path)
    if t.zone == "desk-state" and t.site_rel.startswith("state/memory"):
        p = Path(path)
        size = p.stat().st_size if p.is_file() else 0
        detail = (ti.get("content") or ti.get("new_string") or "")
        Ledger(site).event("memory.changed", "desk", None, {"path": t.site_rel, "bytes": size,
                                                           "tool": data.get("tool_name"),
                                                           "summary": detail[:300]})
    elif t.zone == "config":
        Ledger(site).event("config.changed", "desk", None, {"path": t.site_rel})
    return None


def subagent_start(site: Site, data: dict) -> dict | None:
    role = _role_of(site, data)
    if role.startswith("foreign:"):
        return None
    led = Ledger(site)
    started = {e["refs"][0] for e in led.load("event") if e["type"] == "agent.started" and e["refs"]}
    pending = [e for e in led.load("event") if e["type"] in ("wi.dispatched", "checker.dispatched")
               and e["payload"].get("role") == role and e["id"] not in started]
    if not pending:
        return None
    ev = pending[0]
    led.event("agent.started", role, ev["wi"], {"agent_id": data.get("agent_id"), "brief": ev["payload"].get("brief")}, [ev["id"]])
    return None


def subagent_stop(site: Site, data: dict) -> None:
    role = _role_of(site, data)
    if role.startswith("foreign:"):
        return None
    led = Ledger(site)
    wi = _agent_wi(led, data.get("agent_id"))
    tpath = data.get("agent_transcript_path")
    usage = transcript_usage(Path(tpath)) if tpath else {"coverage": "none", "reason": "runtime did not supply a transcript path"}
    led.event("agent.finished", role, wi, {"agent_id": data.get("agent_id")})
    led.append("run", "agent", role, wi, {"run_type": "agent", "status": "completed", "agent_id": data.get("agent_id"),
                                          "runtime": "claude-code", "usage": usage})
    return None


def session_start(site: Site, data: dict) -> dict:
    from ..selftest import session_checks

    led = Ledger(site)
    checks = session_checks(site)  # before this session writes anything
    led.append("session", "start", "desk", None, {"phase": "start", "source": data.get("source"),
                                                  "session_id": data.get("session_id"), "checks": checks})
    persona = _persona(site)
    handoff = site.state / "memory" / "handoff.md"
    parts = [f"DUREH session start for site {site.root}.",
             "Persona: " + json.dumps(persona, ensure_ascii=False) if persona else "Persona: not configured.",
             render_status(status(site)), "Checks: " + "; ".join(checks)]
    if handoff.is_file():
        parts.append("Handoff from the previous desk session:\n" + handoff.read_text(encoding="utf-8")[:4000])
    return {"hookSpecificOutput": {"hookEventName": "SessionStart", "additionalContext": "\n\n".join(parts)}}


def session_end(site: Site, data: dict) -> None:
    from ..state import save_state

    led = Ledger(site)
    led.append("session", "end", "desk", None, {"phase": "end", "reason": data.get("reason"),
                                                "session_id": data.get("session_id")})
    save_state(site, f"session end {data.get('session_id', '')}".strip())
    return None


def _audit_denial(site: Site, data: dict, out: dict | None) -> dict | None:
    if out and out.get("hookSpecificOutput", {}).get("permissionDecision") == "deny":
        role = _role_of(site, data)
        ti = data.get("tool_input") or {}
        target = ti.get("file_path") or ti.get("command") or ti.get("subagent_type") or ti.get("url") or ""
        try:
            Ledger(site).event("guard.denied", role if role in site.org.roles else "desk", None,
                               {"tool": data.get("tool_name"), "role": role, "agent_id": data.get("agent_id"),
                                "target": str(target)[:300],
                                "reason": out["hookSpecificOutput"].get("permissionDecisionReason", "")[:500]})
        except DurehError:
            pass
    return out


def handle(site: Site, data: dict) -> dict | None:
    event = data.get("hook_event_name")
    try:
        if event == "PreToolUse":
            return _audit_denial(site, data, pre_tool_use(site, data))
        if event == "PostToolUse":
            return post_tool_use(site, data)
        if event == "SubagentStart":
            return subagent_start(site, data)
        if event == "SubagentStop":
            return subagent_stop(site, data)
        if event == "SessionStart":
            return session_start(site, data)
        if event == "SessionEnd":
            return session_end(site, data)
    except DurehError as exc:
        if event == "PreToolUse":
            return _deny(f"harness error, failing closed: {exc}")
        return {"systemMessage": f"DUREH hook error ({event}): {exc}"}
    return None
