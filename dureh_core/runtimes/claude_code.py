def _strip_heredocs(command: str) -> str:
    """Drop heredoc bodies (stdin data) and keep everything shells execute, tracking quotes and comments."""
    out, i, n, quote, pending = [], 0, len(command), None, []
    while i < n:
        c = command[i]
        if quote:
            if c == "\\" and quote == '"' and i + 1 < n:
                out.append(command[i:i + 2])
                i += 2
                continue
            quote = None if c == quote else quote
            out.append(c)
            i += 1
            continue
        if c == "\\" and i + 1 < n:
            out.append(command[i:i + 2])
            i += 2
            continue
        if c in "'\"":
            quote = c
        elif c == "#" and (i == 0 or command[i - 1] in " \t\n;&|"):
            j = command.find("\n", i)
            j = n if j < 0 else j
            out.append(command[i:j])
            i = j
            continue
        elif command.startswith("<<", i) and not command.startswith("<<<", i):
            j = i + 2
            strip = j < n and command[j] == "-"
            j += strip
            while j < n and command[j] in " \t":
                j += 1
            k, word = j, []
            while k < n and command[k] not in " \t\n;&|<>()":
                if command[k] in "'\"":
                    e = command.find(command[k], k + 1)
                    if e < 0:
                        break
                    word.append(command[k + 1:e])
                    k = e + 1
                else:
                    word.append(command[k + 1] if command[k] == "\\" and k + 1 < n else command[k])
                    k += 2 if command[k] == "\\" else 1
            if word:
                pending.append(("".join(word), strip))
            out.append(command[i:k])
            i = k
            continue
        elif c == "\n" and pending:
            out.append(c)
            i += 1
            for delim, strip in pending:
                while i < n:
                    e = command.find("\n", i)
                    line, i = command[i:e if e >= 0 else n], (e + 1 if e >= 0 else n)
                    if (line.lstrip("\t") if strip else line) == delim:
                        break
            pending = []
            continue
        out.append(c)
        i += 1
    return "".join(out)


_REDIRECT_OPS = _REDIRECTS | {">&", "<", "<&", "<>", "&>", "&>>", "<<<"}


def _split_redirects(words: list[str]) -> tuple[list[str], list[str]]:
    """(words without redirections, file targets of output redirections). `2>/dev/null` arrives as
    `2`, `>`, `/dev/null`: an fd number right before an operator belongs to the redirection, and
    duplications (`>&2`, `2>&1`) and /dev/* write no file (UR-20261003-05)."""
    out, targets, i = [], [], 0
    while i < len(words):
        w = words[i]
        if w.isdigit() and i + 1 < len(words) and words[i + 1] in _REDIRECT_OPS:
            i += 1
            continue
        if w in _REDIRECT_OPS:
            tgt = words[i + 1] if i + 1 < len(words) else ""
            if w in _REDIRECTS | {"&>", "&>>", "<>"} and tgt and not tgt.startswith("&") \
                    and not tgt.startswith("/dev/") and not (w in (">&",) and tgt.isdigit()):
                targets.append(tgt)
            i += 2
            continue
        out.append(w)
        i += 1
    return out, targets


def _segments(command: str) -> list[list[str]]:
    lex = shlex.shlex(_strip_heredocs(command).replace("\n", " ; "), posix=True, punctuation_chars=";&|<>")
    lex.whitespace_split = True
    tokens = list(lex)
    segs, cur = [], []
    for t in tokens:
        if t in _SEPARATORS:
            segs.append(cur)
            segs.append([t])
            cur = []
        else:
            cur.append(t)
    segs.append(cur)
    return [s for s in segs if s]


_GIT_READ = {"status", "log", "diff", "show", "rev-parse", "ls-files", "ls-tree", "cat-file", "blame", "grep",
             "describe", "shortlog", "rev-list", "merge-base", "show-ref", "for-each-ref", "version", "help",
             "whatchanged", "name-rev", "count-objects", "check-ignore", "diff-tree", "diff-files", "diff-index", "var"}
_GIT_BRANCH_WRITE = {"-d", "-D", "-m", "-M", "-c", "-C", "-f", "--delete", "--move", "--copy", "--force",
                     "--set-upstream-to", "-u", "--unset-upstream", "--edit-description", "-t", "--track"}


def _git_reads(sub: str, args: list[str]) -> bool:
    if sub in _GIT_READ:
        return True
    pos = [a for a in args if not a.startswith("-")]
    if sub == "branch":
        listing = {"-a", "--all", "-r", "--remotes", "-l", "--list", "--contains", "--no-contains", "--merged",
                   "--no-merged", "--points-at", "--show-current", "-v", "-vv", "--verbose", "--format", "--sort"}
        if any(a.split("=")[0] in listing for a in args) and not any(a.split("=")[0] in _GIT_BRANCH_WRITE for a in args):
            return True
        return not pos and not any(a.split("=")[0] in _GIT_BRANCH_WRITE for a in args)
    if sub == "archive":  # writes only through -o/--output, which _git_check checks as a write
        return not any(a in ("-o", "--output") or a.startswith("--output=") for a in args)
    if sub == "tag":
        return not pos or any(a in ("-l", "--list") for a in args)
    if sub in ("stash", "worktree", "notes"):
        return bool(pos) and pos[0] in ("list", "show")
    if sub == "reflog":
        return not pos or pos[0] == "show"
    if sub == "config":
        return any(a.split("=")[0] in ("--get", "--get-all", "--get-regexp", "--list", "-l", "--show-origin") for a in args)
    if sub == "remote":
        return not pos or pos[0] in ("show", "get-url")
    if sub == "submodule":
        return not pos or pos[0] == "status"
    return False


def _git_check(site: Site, words: list[str], cwd: Path, agent_wi: str | None, agent_id: str | None) -> str | None:
    """Reason to deny a git command, or None. Writes are allowed only in the bound WI's worktree or scratch."""
    i, repo = 1, cwd
    while i < len(words) and words[i].startswith("-"):
        w = words[i]
        if w.split("=")[0] in ("--git-dir", "--work-tree", "--namespace", "--exec-path"):
            return f"git {w.split('=')[0]} cannot be checked; run git inside your WI worktree"
        if w == "-C" and i + 1 < len(words):
            repo = (repo / os.path.expanduser(words[i + 1])).resolve()
            i += 2
        elif w == "-c":
            i += 2
        else:
            i += 1
    if i >= len(words):
        return None
    sub, args = words[i], words[i + 1:]
    if _git_reads(sub, args):
        return None
    pos = [a for a in args if not a.startswith("-")]
    if sub == "init" and pos:
        repo = (repo / os.path.expanduser(pos[-1])).resolve()
    elif sub == "clone":
        if len(pos) < 2:
            return "git clone needs an explicit destination inside your WI worktree or scratch space"
        repo = (repo / os.path.expanduser(pos[-1])).resolve()
    if sub == "archive":
        out = next((args[k + 1] for k, a in enumerate(args[:-1]) if a in ("-o", "--output")), None) \
            or next((a.split("=", 1)[1] for a in args if a.startswith("--output=")), None)
        t_out = classify(site, (cwd / os.path.expanduser(out)).resolve(), cwd)
        if t_out.zone == "scratch" or (t_out.zone == "worktree" and (not agent_wi or t_out.wi == agent_wi)):
            return None
        return f"git archive -o writes only inside your WI worktree or scratch space (target is {t_out.site_rel or out})"
    t = classify(site, repo, cwd)
    if t.zone == "scratch":
        return None
    if t.zone == "worktree":
        if agent_id and not agent_wi:
            return f"git {sub} writes; this agent is not bound to a work item, so it may not write any worktree"
        if agent_wi and t.wi != agent_wi:
            return f"git {sub} writes the worktree of {t.wi}; this agent is dispatched for {agent_wi}"
        return None
    return f"git {sub} writes only inside your WI worktree or scratch space (target is {t.site_rel or repo})"


