_SCAN_VALUE_OPTS = {
    "grep": {"-e", "-f", "-A", "-B", "-C", "-m", "-d", "-D", "--include", "--exclude", "--exclude-dir", "--exclude-from",
             "--regexp", "--file", "--color", "--colour", "--label", "--binary-files", "--max-count", "--context"},
    "rg": {"-e", "-f", "-g", "-t", "-T", "-A", "-B", "-C", "-m", "-M", "-j", "-E", "-r", "--regexp", "--file", "--glob",
           "--iglob", "--type", "--type-not", "--type-add", "--max-depth", "--max-count", "--max-columns", "--threads",
           "--encoding", "--replace", "--color", "--colors", "--sort", "--sortr", "--pre", "--pre-glob", "--context",
           "--after-context", "--before-context", "--context-separator", "--path-separator", "--max-filesize",
           "--dfa-size-limit", "--regex-size-limit", "--ignore-file"},
    "tree": {"-L", "-P", "-I", "-o", "-H", "-T", "--filelimit", "--charset", "--timefmt", "--sort"},
    "du": {"-d", "-B", "-t", "-X", "--max-depth", "--block-size", "--threshold", "--exclude", "--exclude-from"},
    "ls": {"-w", "-I", "-T", "--width", "--ignore", "--tabsize", "--block-size", "--time-style", "--format", "--sort",
           "--color", "--quoting-style", "--hide", "--indicator-style", "--time"},
}
_FIND_LEAD = re.compile(r"^-[HLP]+$|^-[DO]")
_SCAN_VARS = re.compile(r"\$\{?([A-Za-z_][A-Za-z0-9_]*)\}?")


def _positional(first: str, words: list[str]) -> list[str]:
    """Arguments that are not options (and not an option's value) of a scan command."""
    out, i, take = [], 0, _SCAN_VALUE_OPTS.get(first, set())
    while i < len(words):
        w = words[i]
        if w == "--":
            out += words[i + 1:]
            break
        if w.startswith("-") and w != "-":
            if w in take and "=" not in w:
                i += 1  # the option's value
        else:
            out.append(w)
        i += 1
    return out


def _has_flag(words: list[str], short: str, long: str) -> bool:
    return any(w == long or (w.startswith("-") and not w.startswith("--") and short in w[1:]) for w in words)


def scan_roots(first: str, words: list[str]) -> list[str] | None:
    """The directories a filesystem scan starts from, or None when the command is not a scan: `find` (always),
    `grep -r/-R`, `rg` (always), `du` (always), `ls -R`, `tree`; no path argument means the current directory."""
    args = words[1:]
    if first == "find":
        roots, i = [], 0
        while i < len(args) and _FIND_LEAD.match(args[i]):
            i += 1
        while i < len(args) and not args[i].startswith("-") and args[i] not in ("(", "!", ","):
            roots.append(args[i])
            i += 1
        return roots or ["."]
    if first in ("grep", "egrep", "fgrep"):
        if not _has_flag(args, "r", "--recursive") and not _has_flag(args, "R", "--dereference-recursive"):
            return None
        pos = _positional("grep", args)
        if not any(a.startswith(("-e", "-f", "--regexp", "--file")) for a in args):
            pos = pos[1:]  # the pattern
        return pos or ["."]
    if first == "rg":
        pos = _positional("rg", args)
        if not any(a.startswith(("-e", "-f", "--regexp", "--file", "--files", "--type-list")) for a in args):
            pos = pos[1:]
        return pos or ["."]
    if first == "du":
        return _positional("du", args) or ["."]
    if first == "tree":
        return _positional("tree", args) or ["."]
    if first in ("ls", "dir", "vdir"):
        if not _has_flag(args, "R", "--recursive"):
            return None
        return _positional("ls", args) or ["."]
    return None


def _scan_check(site: Site, first: str, words: list[str], cwd: Path) -> str | None:
    roots = scan_roots(first, words)
    if roots is None:
        return None
    env = site.env()
    known = {"HOME": env.get("HOME", os.path.expanduser("~")), "PWD": str(cwd), "TMPDIR": env.get("TMPDIR", ""),
             "DUREH_SITE": str(site.root), "DUREH_ROOT": str(HARNESS_ROOT), "USER": env.get("USER", "")}
    for raw in roots:
        path = _SCAN_VARS.sub(lambda m: known.get(m.group(1), m.group(0)), raw)
        if "$" in path:
            continue  # an unknown variable: not checkable here; the write and git rules still apply
        path = os.path.expanduser(path)
        if classify(site, path, cwd).zone != "outside":
            continue
        shown = raw if raw != "." else f". (cwd {cwd})"
        tmp = next(iter(scratch_roots()), Path("/tmp"))
        return (f"`{first} {shown}` scans outside the allowed roots (whole-filesystem scans run for hours and outlive"
                f" the agent). Search inside your WI worktree ({site.worktrees}/<WI>), the site ({site.root}: modules/,"
                f" projects/, scratch/, logs/), scratch space ({tmp}) or the harness ({HARNESS_ROOT}), for example"
                f" `{first} {site.worktrees}/<WI> ...`; for a known file use its exact path.")
    return None


def _marked(original: str, agent_id: str, simple: bool) -> str:
    """The command with DUREH_AGENT_ID in its environment, so leftovers can be found when the agent ends."""
    ident = f"DUREH_AGENT_ID={shlex.quote(agent_id)}"
    return f"{ident} {original}" if simple else f"export {ident}\n{original}"


WAIT_HINT = ("do not wait for jobs in the session: end your turn; the desk re-dispatches you when `dureh slurm watch`"
             " reports the job")
_WAIT_FORM = re.compile(r"(?<![\w-])(squeue|sacct|sleep|until|while|scontrol\s+show\s+job|slurm\s+(wait|status))(?![\w-])")


def _wait_hint(reason: str, command: str, always: bool = False) -> str:
    """Release 30: a refused form that looks like waiting for a job gets the rule that replaces the wait."""
    return f"{reason}; {WAIT_HINT}" if always or _WAIT_FORM.search(command) else reason


def guard_bash(site: Site, role: str, data: dict) -> dict | None:
    ti = data.get("tool_input") or {}
    original = ti.get("command") or ""
    command = _LITERAL_SUBST.sub("LITERAL", original)  # checked form; the original runs
    command = re.sub(r"\$\(\s*pwd\s*\)", "$PWD", command)  # same value as $PWD, which is not a command
    if ti.get("run_in_background"):
        return _deny(_wait_hint("no hidden background work in the session; submit computation with `dureh slurm submit`",
                                original, always=True))
    if "`" in command or "$(" in command:
        if role != "desk":
            return _deny(_wait_hint("command substitution cannot be checked; run the parts as separate commands", original))
    try:
        segs = _segments(command)
    except ValueError as exc:
        return _deny(_wait_hint(f"cannot parse the command ({exc}); simplify it", original))
    cwd = Path(data.get("cwd") or site.root)
    scheduler_only = _scheduler_only(site)
    words_only = [s for s in segs if s[0] not in _SEPARATORS]
    if any(s == ["&"] for s in segs):
        return _deny(_wait_hint("no background jobs (`&`) in the session; use the scheduler", original))
    agent_id = data.get("agent_id")
    led = Ledger(site)
    agent_wi = _bind(led, role, data, "first-tool") if agent_id else None
    dureh_seen = keyword_lead = False
    literals: dict[str, str] = {}  # NAME=value assignments earlier in this line
    for seg in words_only:
        words = list(seg)
        if all(re.match(r"^[A-Za-z_][A-Za-z0-9_]*=", w) for w in words):
            for w in words:
                name, _, value = w.partition("=")
                literals[name] = value
        m = re.match(r"^\$\{?([A-Za-z_][A-Za-z0-9_]*)\}?$", words[0]) if words else None
        if m and m.group(1) in literals and _is_dureh(literals[m.group(1)], site):
            words[0] = literals[m.group(1)]  # `B=bin/dureh; $B ...` is a written-out dureh call
        env_assign = []
        while words and re.match(r"^[A-Za-z_][A-Za-z0-9_]*=", words[0]):
            env_assign.append(words.pop(0))
        if any(a.startswith("DUREH_") for a in env_assign):
            return _deny("DUREH_* variables are set by the harness, not by the command")
        if role != "desk" and any(a.startswith("GIT_") for a in env_assign):
            return _deny("GIT_* variables redirect git and cannot be checked; run git inside your WI worktree")
        # loops, conditions and groups are fine: the wrapper below exports the identity for the whole line
        if words and (words[0] in _KEYWORDS or words[0].startswith("(")):
            keyword_lead = True  # `ID=x (cmd)` or `ID=x if ...` is not valid shell; such a line takes the wrapper
        words = _strip_lead(words)
        if not words:
            continue
        first = os.path.basename(words[0])
        if role != "desk":
            if words[0].startswith("$"):
                return _deny("a command named by a variable cannot be checked; write the command out"
                             " (for several work items: `bin/dureh wi show --wi A --wi B`)")
            if not _is_dureh(words[0], site) and any(_names_harness(w) for w in words):
                return _deny("call the harness only as `bin/dureh <command>`, written out (not through an interpreter "
                             "or another path), so the hook can set your identity")
        if role != "desk" and (first in _INTERPRETERS or re.match(r"python3?\.\d+$", first)) \
                and any(w in ("<<", "<<-", "<<<") for w in words):
            return _deny(_wait_hint(f"a heredoc or here-string fed to `{first}` runs its body, which cannot be checked; "
                                    "write a script file in your scope and run it", original))
        if first in ALWAYS_DENY_FIRST:
            return _deny(_wait_hint(ALWAYS_DENY_FIRST[first], original))
        if any(fnmatchcase(first, pat) for pat in scheduler_only):
            return _deny(f"`{first}` runs only as a scheduler job; use `dureh slurm submit`")
        if first == "git" and "push" in words[1:3]:
            return _deny("pushes go through `dureh push` with a Director decision bound to the revision")
        if first == "git" and role != "desk":
            why = _git_check(site, words, cwd, agent_wi, agent_id)
            if why:
                return _deny(why)
        if first == "datalad" and role != "desk":
            why = _datalad_check(site, words, cwd, agent_wi, agent_id)
            if why:
                return _deny(why)
        if first == "rm" and any(w.startswith("-") and ("r" in w or "R" in w) for w in words[1:]):
            return _deny("recursive deletion goes through `dureh purge`")
        if role != "desk":
            why = _scan_check(site, first, words, cwd)
            if why:
                return _deny(why)
        if first == "cd" and len(words) > 1:
            cwd = (cwd / os.path.expanduser(words[1])).resolve()
            continue
        if _is_dureh(words[0], site):
            if "--actor" in words and words[words.index("--actor") + 1: words.index("--actor") + 2] != [role]:
                return _deny("--actor must be your own role; the hook sets identity")
            if "--site" in words and words[words.index("--site") + 1: words.index("--site") + 2] != [str(site.root)]:
                return _deny("dureh commands must target this site")
            dureh_seen = True
            first = "dureh"  # its arguments are not write targets; its redirects are checked below
        words, targets = _split_redirects(words)
        args = [w for w in words[1:] if not w.startswith("-")]
        if first == "tee":
            targets += args
        elif first in ("cp", "mv", "install", "rsync", "ln") and args:
            targets.append(args[-1])
            if first == "mv":
                targets += args[:-1]
        elif first == "mkdir":
            # a directory that is the root of an allowed `<dir>/**` scope is inside that scope (UR-20261003-04)
            targets += [a.rstrip("/") + "/.dureh-dir" for a in args]
        elif first in ("rm", "touch", "rmdir", "truncate", "chmod", "chown"):
            targets += args[1:] if first in ("chmod", "chown") else args
        elif first == "sed" and any(w.startswith("-i") for w in words[1:]):
            targets += args[1:]
        elif first in ("git",) and len(words) > 1 and words[1] in ("mv", "rm"):
            targets += [w for w in words[2:] if not w.startswith("-")]
        for tgt in targets:
            if tgt in ("/dev/null", "/dev/stdout", "/dev/stderr") or tgt.startswith("&"):
                continue
            ok, why = _write_decision(site, role, Path(os.path.expanduser(tgt)), cwd, agent_wi, agent_id)
            if not ok:
                return _deny(f"write to {tgt.removesuffix('/.dureh-dir')}: {why}")
    if dureh_seen:  # every segment passed its own checks; give each dureh in the line this role's identity
        ident = f"DUREH_ACTOR={shlex.quote(role)}" + (f" DUREH_AGENT_ID={shlex.quote(agent_id)}" if agent_id else "")
        new_input = dict(ti)
        new_input["command"] = f"{ident} {original}" if len(words_only) == 1 and not keyword_lead else f"( export {ident}\n{original}\n)"
        return {"hookSpecificOutput": {"hookEventName": "PreToolUse", "permissionDecision": "allow",
                                       "permissionDecisionReason": "DUREH harness tool; identity set by hook",
                                       "updatedInput": new_input}}
    if agent_id and role != "desk" and words_only:
        # release 27: every process an agent starts carries its agent id, so leftovers are found when it ends.
        # No permissionDecision: the rewritten command goes through Claude Code's normal permission path (rules,
        # auto-mode classifier). Measured 2026-10-05 (labs/hook-test): updatedInput without a decision is applied
        # before that check in both the default path and `--permission-mode auto`.
        new_input = dict(ti)
        new_input["command"] = _marked(original, agent_id, len(words_only) == 1 and not keyword_lead)
        return {"hookSpecificOutput": {"hookEventName": "PreToolUse", "updatedInput": new_input}}
    return None


def _record_spawn(led: Ledger, role: str, target: str, wi: str, digest: str, ti: dict) -> dict | None:
    events = led.events(wi)
    prepared = [e for e in events if e["type"] == "dispatch.prepared" and e["payload"].get("brief") == digest]
    if not prepared:
        return _deny(f"no recorded brief {digest} for {wi}")
    if prepared[-1]["payload"].get("by") != role:
        return _deny(f"brief {digest} was prepared by {prepared[-1]['payload'].get('by')}, not {role}")
    consumed = [e for e in events if e["type"] in ("wi.dispatched", "checker.dispatched") and e["payload"].get("brief") == digest]
    if consumed:
        return _deny(f"brief {digest} was already used; prepare a new brief")
    if prepared[-1]["payload"].get("worktree"):
        from ..workflow import worktree_problem

        wt = led.site.worktrees / wi  # where the site is now; the recorded path may predate a move
        err = worktree_problem(wt, wi, led.site)
        if err:
            return _deny(f"worktree {wt} is broken ({err}); the desk repairs it with `dureh worktree repair --wi {wi}`")
    try:
        etype = "checker.dispatched" if prepared[-1]["payload"].get("checking") else "wi.dispatched"
        led.event(etype, role, wi, {"role": target, "brief": digest, "by": role,
                                    "model": prepared[-1]["payload"].get("model"),
                                    "background": bool(ti.get("run_in_background"))}, [prepared[-1]["id"]])
    except DurehError as exc:
        return _deny(str(exc))
    return None


def pre_tool_use(site: Site, data: dict) -> dict | None:
    tool = data.get("tool_name") or ""
    role = _role_of(site, data)
    if role.startswith("foreign:"):
        if tool in WRITE_TOOLS | SPAWN_TOOLS or tool == "Bash":
            return _deny(f"{role[8:]} is not a DUREH role; spawn DUREH roles only")
        return None
    org = site.org
    led = Ledger(site)
    ti = data.get("tool_input") or {}
    if tool in SPAWN_TOOLS:
        if role != "desk":
            _bind(led, role, data, "first-tool")
        target = ti.get("subagent_type") or "general-purpose"
        if target not in org.roles or target == "desk":
            return _deny(f"`{target}` is not a DUREH role; research goes to `researcher`, documents to `doc-writer`")
        if target not in org.role(role).may_dispatch:
            return _deny(f"{role} may not dispatch {target}")
        m = BRIEF_RE.search(ti.get("prompt") or "")
        if not m:
            return _deny(f"spawn needs a brief: run `{site.root}/bin/dureh dispatch brief --wi <WI>` and pass its output as the prompt")
        wi, brief_role, digest = m.groups()
        if brief_role != target:
            return _deny(f"the brief is for {brief_role}, not {target}")
        from ..workday import gate

        why = gate(site, wi, checking=target == "checker")
        if why:
            return _deny(why)
        with led.lock():
            return _record_spawn(led, role, target, wi, digest, ti)
    if tool in WRITE_TOOLS:
        path = ti.get("file_path") or ti.get("notebook_path")
        if not path:
            return _deny("write without a path")
        agent_wi = _bind(led, role, data, "first-tool")
        ok, why = _write_decision(site, role, Path(path), Path(data.get("cwd") or site.root), agent_wi,
                                  data.get("agent_id"))
        if not ok:
            return _deny(why)
        t = classify(site, path)
        if t.zone == "desk-state" and t.site_rel.startswith("state/memory") and tool == "Write":
            cap = int(site.limit("memory_cap_bytes", 65536))
            mem = site.state / "memory"
            current = sum(f.stat().st_size for f in mem.rglob("*") if f.is_file() and f.resolve() != Path(path).resolve())
            new = len((ti.get("content") or "").encode("utf-8"))
            if current + new > cap:
                return _deny(f"desk memory would grow to {current + new} bytes, over the {cap}-byte cap; summarize first")
        return None
    if tool == "Bash":
        return guard_bash(site, role, data)
    if tool in NETWORK_TOOLS and role not in ("desk", "researcher"):
        return _deny("network access is limited to the desk and researcher")
    return None


def post_tool_use(site: Site, data: dict) -> None:
    ti = data.get("tool_input") or {}
    path = ti.get("file_path")
    if not path or _role_of(site, data) != "desk":
        return None
    t = classify(site, path)
    if t.zone == "desk-state" and t.site_rel.startswith("state/memory"):
        p = Path(path)
        size = p.stat().st_size if p.is_file() else 0
        detail = (ti.get("content") or ti.get("new_string") or "")
        Ledger(site).event("memory.changed", "desk", None, {"path": t.site_rel, "bytes": size,
                                                           "tool": data.get("tool_name"),
                                                           "summary": detail[:300]})
    elif t.zone == "config":
        Ledger(site).event("config.changed", "desk", None, {"path": t.site_rel})
    return None


def subagent_start(site: Site, data: dict) -> dict | None:
    role = _role_of(site, data)
    if role.startswith("foreign:"):
        return None
    _bind(Ledger(site), role, data, "start")
    return None


def _candidates(led: Ledger, role: str) -> list[dict]:
    """Unbound dispatches of `role` that are still live: the latest dispatch of a WI still in that state."""
    events = led.events()
    started = {e["refs"][0] for e in events if e["type"] == "agent.started" and e["refs"]}
    latest: dict[tuple, dict] = {}
    for e in events:
        if e["type"] in ("wi.dispatched", "checker.dispatched"):
            latest[(e["wi"], e["type"])] = e
    live = {"wi.dispatched": "dispatched", "checker.dispatched": "staged"}
    return [e for e in latest.values() if e["payload"].get("role") == role and e["id"] not in started
            and led.wi_status(e["wi"])["status"] == live[e["type"]]]


def _bind(led: Ledger, role: str, data: dict, at: str) -> str | None:
    """Bind an agent to its WI: by the brief in its own prompt, else (after start) by order when one candidate exists.

    With a single live candidate, that dispatch must be this agent's own: its spawn recorded it and no
    other agent can have taken it, because other agents bind only by their own brief or the same rule.
    """
    agent_id = data.get("agent_id")
    if not agent_id:
        return None
    digest = _brief_in_transcript(data)
    with led.lock():
        bound = _agent_wi(led, agent_id)
        if bound:
            return bound
        pending = _candidates(led, role)
        exact = [e for e in pending if digest and e["payload"].get("brief") == digest]
        if exact:
            ev, how = exact[0], "brief"
        elif not digest and len(pending) == 1 and at != "start":
            ev, how = pending[0], "order"
        else:
            if at == "start" and pending:
                # the runtime has usually not written the transcript yet: note the start, bind at the first tool call
                led.event("agent.started", role, None, {"agent_id": agent_id, "bound_by": "deferred", "bound_at": at,
                                                        "prompt_brief": None, "runtime_pid": procs.runtime_pid()})
            return None
        led.event("agent.started", role, ev["wi"], {"agent_id": agent_id, "brief": ev["payload"].get("brief"),
                                                    "bound_by": how, "bound_at": at, "prompt_brief": digest,
                                                    "runtime_pid": procs.runtime_pid()}, [ev["id"]])
        return ev["wi"]


def _transcripts(data: dict) -> list[Path]:
    """Where the subagent's own transcript can be. Measured on Claude Code 2.1: a subagent of session
    <dir>/<session>.jsonl writes <dir>/<session>/subagents/agent-<agent_id>.jsonl, prompt on line 1."""
    agent_id = data.get("agent_id")
    out = [Path(data["agent_transcript_path"])] if data.get("agent_transcript_path") else []
    tp = data.get("transcript_path")
    if tp and agent_id:
        tp = Path(tp)
        name = f"agent-{agent_id}.jsonl"
        out += [tp] if tp.name == name else [tp.with_suffix("") / "subagents" / name,
                                              tp.parent / "subagents" / name]
    return out


def _brief_in_transcript(data: dict) -> str | None:
    """The brief digest from the subagent's own prompt (the first DUREH-BRIEF line of its transcript)."""
    for path in _transcripts(data):
        try:
            with open(path, encoding="utf-8", errors="replace") as fh:
                m = BRIEF_RE.search(fh.read(65536))
        except OSError:
            continue
        if m:
            return m.group(3)
    return None


def subagent_stop(site: Site, data: dict) -> None:
    role = _role_of(site, data)
    if role.startswith("foreign:"):
        return None
    led = Ledger(site)
    wi = _bind(led, role, data, "stop")
    tpath = data.get("agent_transcript_path")
    usage = transcript_usage(Path(tpath)) if tpath else {"coverage": "none", "reason": "runtime did not supply a transcript path"}
    agent_id = data.get("agent_id")
    leftovers = _cleanup_agent(led, role, wi, agent_id)
    led.event("agent.finished", role, wi, {"agent_id": agent_id, "leftovers_killed": len(leftovers.get("killed") or [])})
    led.append("run", "agent", role, wi, {"run_type": "agent", "status": "completed", "agent_id": agent_id,
                                          "runtime": "claude-code", "usage": usage})
    return None


def _cleanup_agent(led: Ledger, role: str, wi: str | None, agent_id: str | None) -> dict:
    """Release 27: kill what the finished agent left running (processes marked with its id, same session job)
    and record it as `agent.cleaned`. Never the session: this hook's own ancestors and the recorded runtime
    pid are protected; a failure here never breaks the stop hook."""
    if not agent_id:
        return {}
    protect = set()
    for ev in reversed(led.load("event")):
        if ev["type"] == "agent.started" and ev["payload"].get("agent_id") == agent_id:
            if ev["payload"].get("runtime_pid"):
                protect.add(int(ev["payload"]["runtime_pid"]))
            break
    try:
        result = procs.kill_leftovers(agent_id, protect)
    except Exception as exc:  # noqa: BLE001 - cleanup is best effort
        result = {"method": "environ-marker", "agent_id": agent_id, "scanned": 0, "killed": [], "errors": [{"error": str(exc)}]}
    if result.get("killed") or result.get("errors"):
        try:
            led.event("agent.cleaned", role, wi, result)
        except DurehError:
            pass
    return result


def session_start(site: Site, data: dict) -> dict:
    from ..selftest import session_checks

    led = Ledger(site)
    checks = session_checks(site)  # before this session writes anything
    led.append("session", "start", "desk", None, {"phase": "start", "source": data.get("source"),
                                                  "session_id": data.get("session_id"), "checks": checks})
    persona = _persona(site)
    handoff = site.state / "memory" / "handoff.md"
    parts = [f"DUREH session start for site {site.root}.",
             "Persona: " + json.dumps(persona, ensure_ascii=False) if persona else "Persona: not configured.",
             render_status(status(site)), "Checks: " + "; ".join(checks)]
    if handoff.is_file():
        parts.append("Handoff from the previous desk session:\n" + handoff.read_text(encoding="utf-8")[:4000])
    return {"hookSpecificOutput": {"hookEventName": "SessionStart", "additionalContext": "\n\n".join(parts)}}


def session_end(site: Site, data: dict) -> None:
    from ..state import save_state

    led = Ledger(site)
    led.append("session", "end", "desk", None, {"phase": "end", "reason": data.get("reason"),
                                                "session_id": data.get("session_id")})
    save_state(site, f"session end {data.get('session_id', '')}".strip())
    return None


def _audit_denial(site: Site, data: dict, out: dict | None) -> dict | None:
    if out and out.get("hookSpecificOutput", {}).get("permissionDecision") == "deny":
        role = _role_of(site, data)
        ti = data.get("tool_input") or {}
        target = ti.get("file_path") or ti.get("command") or ti.get("subagent_type") or ti.get("url") or ""
        payload = {"tool": data.get("tool_name"), "role": role, "agent_id": data.get("agent_id"),
                   "target": str(target)[:4000],
                   "reason": out["hookSpecificOutput"].get("permissionDecisionReason", "")[:500]}
        try:
            led = Ledger(site)
            if data.get("agent_id"):
                payload.update(bound_wi=_agent_wi(led, data["agent_id"]), bound_brief=_agent_brief(led, data["agent_id"]),
                               prompt_brief=_brief_in_transcript(data))
            led.event("guard.denied", role if role in site.org.roles else "desk", None, payload)
        except DurehError:
            pass
    return out


def handle(site: Site, data: dict) -> dict | None:
    event = data.get("hook_event_name")
    try:
        if event == "PreToolUse":
            return _audit_denial(site, data, pre_tool_use(site, data))
        if event == "PostToolUse":
            return post_tool_use(site, data)
        if event == "SubagentStart":
            return subagent_start(site, data)
        if event == "SubagentStop":
            return subagent_stop(site, data)
        if event == "SessionStart":
            return session_start(site, data)
        if event == "SessionEnd":
            return session_end(site, data)
    except DurehError as exc:
        if event == "PreToolUse":
            return _deny(f"harness error, failing closed: {exc}")
        return {"systemMessage": f"DUREH hook error ({event}): {exc}"}
    return None
