"""Generated guidance inside each linked project: agent files for project-facing roles and a CLAUDE.md
that explains the project's data flow from its manifest and the site's records.

Written by `dureh adapter sync` and `dureh site link-project`, committed in the project dataset, and
tracked in `<project>/.claude/.dureh-generated.json` so hand edits are reported by the session check.
Files that exist but were not generated by DUREH are never overwritten.
"""
from __future__ import annotations

import json
import subprocess
from pathlib import Path

from . import yamlsub
from .records import Ledger
from .site import Site
from .util import dumps, fail, sha256_bytes, utc_now, write_replace

PROJECT_ROLES = ("data-steward", "pipeline-runner", "interpreter", "doc-writer", "checker")
MANIFEST_REL = ".claude/.dureh-generated.json"
TEMPLATE_REL = "templates/project/CLAUDE.md.template"


def _manifest(root: Path) -> dict:
    p = root / "camri-manifest.yaml"
    return yamlsub.load_file(p) if p.is_file() else {}


def _producers(site: Site, name: str) -> dict[str, list[str]]:
    led = Ledger(site)
    targets = {w["id"]: led.get("work-item", w["id"])["payload"] for w in led.work_items()}
    out: dict[str, list[str]] = {}
    for r in led.load("run"):
        p = r["payload"]
        if p.get("run_type") != "promotion" or targets.get(r["wi"], {}).get("target") != f"projects/{name}":
            continue
        line = f"{r['wi']} ({targets[r['wi']]['role']}), " + (
            f"run {p.get('from_run')}, job {p.get('job_id')}, " if p.get("from_run") else "metadata, ")
        out.setdefault(p["dataset"], []).append(line + f"commit {str(p.get('commit'))[:12]}, {len(p.get('dest') or [])} file(s)")
    return out


def _size(n) -> str:
    return f"{n / 1e9:.1f} GB" if isinstance(n, int) and n >= 1e9 else (f"{n / 1e6:.1f} MB" if isinstance(n, int) else "")


def _link_group(path: str) -> str:
    parts = path.split("/")
    return "/".join(parts[:2] if parts[0] in ("derivatives", "sourcedata") and len(parts) > 2 else parts[:1]) + "/"


def _links(m: dict) -> list[str]:
    links = [x for x in m.get("external_links") or [] if isinstance(x, dict) and x.get("path")]
    if not links:
        return []
    groups: dict[str, list[dict]] = {}
    for x in links:
        groups.setdefault(_link_group(str(x["path"])), []).append(x)
    lines = [f"- {len(links)} links: " + ", ".join(f"{len(v)} under {k}" for k, v in groups.items())
             + " (full list in camri-manifest.yaml `external_links`; symlinks count as self-contained in the dev stage)"]
    for v in list(groups.values())[:3]:
        lines.append(f"- e.g. {v[0]['path']} -> {v[0].get('link_target') or v[0].get('target')}")
    return lines


def _pipeline_label(p: dict) -> str:
    return f"pipeline {p.get('family')} ({p.get('species')}, {p.get('suffix')})"


def _claude_md(site: Site, name: str, root: Path) -> str | None:
    tpl = site.startup / TEMPLATE_REL
    if not tpl.is_file():
        return None
    m = _manifest(root)
    version = m.get("template_version") or (f"manifest schema {m['schema_version']}" if m.get("schema_version") else "unknown")
    head = tpl.read_text(encoding="utf-8").replace("{{template_version}}", str(version))
    ds = m.get("datasets") or {}
    src = m.get("source") or {}
    sw = m.get("software") or {}
    tools = (m.get("provenance") or {}).get("tool_versions") or {}
    pipelines = [p for p in m.get("pipelines") or [] if isinstance(p, dict)]
    derivs = list(ds.get("derivatives") or [])
    for sub in (m.get("datalad") or {}).get("subdatasets") or []:
        path = str(sub.get("path") or "") if isinstance(sub, dict) else ""
        if path.startswith("derivatives/") and path.split("/", 1)[1] not in derivs:
            derivs.append(path.split("/", 1)[1])
    producers = _producers(site, name)
    for d in producers:
        if d.split("/", 1)[1] not in derivs:
            derivs.append(d.split("/", 1)[1])
    lines = [head.rstrip(), "", "<!-- Below: generated by DUREH from camri-manifest.yaml and the site's records;"
             " regenerated by `dureh adapter sync`. Do not edit. -->", "",
             "## Data flow", "",
             "rawbids -> checkpoints -> derivatives -> reports", "",
             "- Versioned: `rawbids/` and `derivatives/<name>/` (DataLad subdatasets), `reports/`.",
             "- Disposable, never versioned: `checkpoints/`, `cache/`.",
             "- `checkpoints/` reach `derivatives/` only through `dureh promote`, run by a dispatched data-steward after a"
             " COMPLETED scheduler run; derivatives are final and never overwritten.", "",
             "## Inputs and links", ""]
    if src:
        where = f" at {src['external_root']}" if src.get("external_root") else ""
        extra = ", ".join(x for x in (_size(src.get("size_bytes")), "external" if src.get("external_root") else "") if x)
        lines.append(f"- source: {src.get('type') or 'unknown'}{where}" + (f" ({extra})" if extra else ""))
    else:
        for key in ("sourcedata", "rawbids"):
            lines.append(f"- {key}: {ds.get(key) or 'not declared'}")
    lines += _links(m)
    camri = tools.get("camri") or sw.get("camri")
    digest = sw.get("container_digest")
    lines += ["", "## Software and containers", "",
              f"- camri {camri or 'not pinned'}" + (f"; container digest {digest}" if digest else "")]
    for c in tools.get("containers") or m.get("containers") or []:
        if isinstance(c, dict):
            lines.append(f"- container {c.get('name')}: {c.get('digest') or 'no digest'}")
    for p in pipelines:
        cv = p.get("camri_version")
        lines.append(f"- {_pipeline_label(p)}: " + (f"camri_version {cv}" if cv else "camri_version not yet registered"))
        for w in p.get("workflows") or []:
            if isinstance(w, dict):
                tags = ", ".join(x for x in ("default" if w.get("default") else "", w.get("role") or "") if x)
                lines.append(f"  - workflow {w.get('name')}" + (f" ({tags})" if tags else ""))
    lines += ["", "## Derivatives and their producers", ""]
    for d in derivs:
        lines.append(f"- derivatives/{d}:")
        made_by = [_pipeline_label(p) for p in pipelines
                   if f"{p.get('family')}_camri_{p.get('species')}_{p.get('suffix')}" == d]
        lines += [f"  - produced by {x}" for x in made_by]
        lines += [f"  - {x}" for x in producers.get(f"derivatives/{d}", [])] or ["  - no promotion recorded yet"]
    if not derivs:
        lines.append("- none declared")
    ex = m.get("execution") or {}
    slurm = ex.get("slurm") or {}
    if ex.get("mode") or slurm:
        sched = (f"mode {ex.get('mode') or 'unknown'}, account {slurm.get('account') or 'unknown'},"
                 f" partition {slurm.get('partition') or 'unknown'}")
    else:
        sched = (f"scheduler {ex.get('scheduler') or 'not set'}, partition {ex.get('partition') or 'not set'},"
                 f" account {ex.get('account') or 'not set'}")
    lines += ["", "## Execution", "",
              f"- {sched}; computation runs only as scheduler jobs (`dureh slurm submit`).",
              "", "## Human in the loop", "",
              "- Gate 1: the Director approves every work item before it is dispatched.",
              "- Gate 2: the Director approves promotion of a verified work item.",
              "- Promotion into `derivatives/`: `dureh promote`, refused without a completed run record."]
    for h in m.get("human_in_the_loop") or []:
        lines.append(f"- {h}")
    return "\n".join(lines) + "\n"


def project_files(site: Site, name: str, root: Path) -> dict[str, str]:
    from .runtimes.claude_code import _agent_file

    files = {f".claude/agents/{r}.md": _agent_file(site, site.org.role(r), project=name)
             for r in PROJECT_ROLES if r in site.org.roles}
    md = _claude_md(site, name, root)
    if md is not None:
        files["CLAUDE.md"] = md
    return files


def _save(site: Site, root: Path, paths: list[str], msg: str) -> None:
    env = site.env()
    if (root / ".datalad").is_dir():
        cmd = ["datalad", "save", "-d", str(root), "-m", msg, *paths]
    elif (root / ".git").exists():
        subprocess.run(["git", "add", "-A", "--", *paths], cwd=root, env=env, check=True, capture_output=True)
        if subprocess.run(["git", "diff", "--cached", "--quiet"], cwd=root, env=env).returncode == 0:
            return
        cmd = ["git", "commit", "-q", "-m", msg]
    else:
        return
    proc = subprocess.run(cmd, cwd=root, env=env, capture_output=True, text=True, timeout=600)
    if proc.returncode != 0:
        fail(f"saving generated project files failed: {(proc.stderr or proc.stdout).strip()[-800:]}")


def generate_projects(site: Site, only: str | None = None) -> list[dict]:
    out = []
    for entry in site.config.get("projects") or []:
        name = entry.get("id")
        if only and name != only:
            continue
        root = site.root / (entry.get("path") or f"projects/{name}")
        if not root.is_dir():
            out.append({"project": name, "changed": False, "error": "project directory is missing"})
            continue
        man_path = root / MANIFEST_REL
        old = json.loads(man_path.read_text(encoding="utf-8")).get("files", {}) if man_path.is_file() else {}
        files, skipped = {}, []
        for rel, text in project_files(site, name, root).items():
            p = root / rel
            if (p.exists() or p.is_symlink()) and rel not in old:
                skipped.append(rel)
            else:
                files[rel] = text
        digests = {rel: sha256_bytes(t.encode("utf-8")) for rel, t in files.items()}
        stale = [rel for rel in old if rel not in digests and (root / rel).is_file()]
        same = digests == old and all((root / rel).is_file() and sha256_bytes((root / rel).read_bytes()) == d
                                      for rel, d in digests.items())
        if same and not stale:
            out.append({"project": name, "changed": False, "files": len(files), "skipped": skipped})
            continue
        for rel in stale:
            (root / rel).unlink()
        for rel, text in files.items():
            (root / rel).parent.mkdir(parents=True, exist_ok=True)
            write_replace(root / rel, text)
        write_replace(man_path, dumps({"generator": "dureh projectgen", "site": site.site_id,
                                       "generated_at": utc_now(), "files": digests}))
        _save(site, root, [*files, *stale, MANIFEST_REL], f"dureh: regenerate project guidance (site {site.site_id})")
        out.append({"project": name, "changed": True, "files": len(files), "skipped": skipped, "removed": stale})
    return out


def project_drift(site: Site) -> list[str]:
    out = []
    for entry in site.config.get("projects") or []:
        root = site.root / (entry.get("path") or f"projects/{entry.get('id')}")
        man_path = root / MANIFEST_REL
        if not man_path.is_file():
            continue
        rel_root = root.relative_to(site.root).as_posix()
        for rel, digest in json.loads(man_path.read_text(encoding="utf-8")).get("files", {}).items():
            p = root / rel
            if not p.is_file():
                out.append(f"{rel_root}: missing generated file {rel}")
            elif sha256_bytes(p.read_bytes()) != digest:
                out.append(f"{rel_root}: generated file was edited by hand: {rel}")
    return out
